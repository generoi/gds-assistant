const {test, expect} = require('@playwright/test');

/**
 * Post-write block validation on the block editor screen: after a server
 * ability saves a post, the chat validates the saved markup with the editor's
 * real block registry and sends the model a follow-up listing the problems.
 */
const WRITE_RESPONSE = [
  'event: conversation_start',
  'data: {"conversation_id":"test-conv-validate","model":"anthropic:sonnet"}',
  '',
  'event: tool_use_start',
  'data: {"id":"toolu_write1","name":"gds__content-update","input":{"type":"pages","id":4242}}',
  '',
  'event: tool_result',
  'data: {"tool_use_id":"toolu_write1","result":{"id":4242,"status":"draft","warnings":["Attribute \\"size\\" is not in the acme/widget schema"]},"is_error":false}',
  '',
  'event: text_delta',
  'data: {"text":"Updated the page."}',
  '',
  'event: message_stop',
  'data: {"stop_reason":"end_turn"}',
  '',
].join('\n');

const FIXED_RESPONSE = [
  'event: conversation_start',
  'data: {"conversation_id":"test-conv-validate","model":"anthropic:sonnet"}',
  '',
  'event: text_delta',
  'data: {"text":"Fixed the blocks."}',
  '',
  'event: message_stop',
  'data: {"stop_reason":"end_turn"}',
  '',
].join('\n');

const SAVED_MARKUP =
  '<!-- wp:paragraph --><p>Fine</p><!-- /wp:paragraph -->' +
  '<!-- wp:paragraph --><div>Broken</div><!-- /wp:paragraph -->' +
  '<!-- wp:acme/widget {"size":2} --><div>x</div><!-- /wp:acme/widget -->';

test.describe('Block validation after a write', () => {
  test('invalid saved blocks are sent back to the model', async ({page}) => {
    const chatBodies = [];
    await page.route('**/gds-assistant/v1/chat', (route) => {
      chatBodies.push(JSON.parse(route.request().postData() || '{}'));
      route.fulfill({
        status: 200,
        headers: {'Content-Type': 'text/event-stream'},
        body: chatBodies.length === 1 ? WRITE_RESPONSE : FIXED_RESPONSE,
      });
    });
    await page.route('**/gds-assistant/v1/block-markup/4242**', (route) =>
      route.fulfill({
        status: 200,
        headers: {'Content-Type': 'application/json'},
        body: JSON.stringify({id: 4242, type: 'page', content: SAVED_MARKUP}),
      }),
    );

    await page.goto('/wp-admin/post-new.php');
    await page.waitForFunction(
      () => !!window.wp?.blocks?.getBlockType?.('core/paragraph'),
    );
    await page.evaluate(() =>
      window.wp.data
        .dispatch('core/preferences')
        ?.set('core/edit-post', 'welcomeGuide', false),
    );

    await page.click('.gds-assistant__trigger');
    await page.locator('.gds-assistant__input').fill('Update page 4242');
    await page.click('.gds-assistant__send');

    const note = page.locator('.gds-assistant__system-note--warning');
    await expect(note).toBeVisible({timeout: 10000});
    await expect(note).toContainText('Post #4242');
    await expect(page.getByText('Fixed the blocks.')).toBeVisible();

    expect(chatBodies).toHaveLength(2);
    const followUp = chatBodies[1].messages[0].content[0].text;
    expect(followUp).toContain('⚠ Block validation:');
    expect(followUp).toContain(
      'core/paragraph (occurrence 2, block 2): Expected tag name `p`, instead saw `div`.',
    );
    expect(followUp).toContain(
      'acme/widget (occurrence 1, block 3): block type is not registered on this site',
    );
    expect(followUp).not.toContain('Content generated by');

    // The card merges gds-mcp's warnings with the validation issues.
    const card = page.locator('.gds-assistant__tool-call').first();
    await expect(
      card.locator('.gds-assistant__tool-call-status--warning'),
    ).toHaveText('⚠ 3');
  });

  test('valid saved blocks send no follow-up', async ({page}) => {
    let chatCalls = 0;
    await page.route('**/gds-assistant/v1/chat', (route) => {
      chatCalls++;
      route.fulfill({
        status: 200,
        headers: {'Content-Type': 'text/event-stream'},
        body: WRITE_RESPONSE,
      });
    });
    await page.route('**/gds-assistant/v1/block-markup/4242**', (route) =>
      route.fulfill({
        status: 200,
        headers: {'Content-Type': 'application/json'},
        body: JSON.stringify({
          id: 4242,
          type: 'page',
          content: '<!-- wp:paragraph --><p>Fine</p><!-- /wp:paragraph -->',
        }),
      }),
    );

    await page.goto('/wp-admin/post-new.php');
    await page.waitForFunction(
      () => !!window.wp?.blocks?.getBlockType?.('core/paragraph'),
    );
    await page.evaluate(() =>
      window.wp.data
        .dispatch('core/preferences')
        ?.set('core/edit-post', 'welcomeGuide', false),
    );

    await page.click('.gds-assistant__trigger');
    await page.locator('.gds-assistant__input').fill('Update page 4242');
    await page.click('.gds-assistant__send');

    await expect(page.getByText('Updated the page.')).toBeVisible({
      timeout: 10000,
    });
    // Give the post-stream check time to run before asserting nothing more.
    await page.waitForTimeout(1500);
    expect(chatCalls).toBe(1);
    await expect(page.locator('.gds-assistant__system-note--warning')).toHaveCount(
      0,
    );
  });
});
