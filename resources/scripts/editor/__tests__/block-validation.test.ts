/// <reference types="@wordpress/jest-console" />
/**
 * Block validation runs the real @wordpress/blocks parser + validator against
 * a small registry: a paragraph and a group registered like their core
 * counterparts (same names, markup and attribute sources), plus the
 * core/missing fallback for unregistered blocks.
 *
 * Gutenberg logs every invalid block to the console (error + warning), which
 * @wordpress/jest-console turns into failures unless a test expects it.
 */

import * as blocks from "@wordpress/blocks";
import { createElement, RawHTML } from "@wordpress/element";

import {
  canValidateBlocks,
  describeValidationIssues,
  formatBlockIssues,
  formatLogArgs,
  validateBlockMarkup,
  type BlockIssue,
} from "../block-validation";
import {
  buildValidationFollowUp,
  writtenPostIds,
} from "../post-write-validation";

type Attrs = Record<string, string>;

beforeAll(() => {
  blocks.registerBlockType("core/paragraph", {
    apiVersion: 3,
    title: "Paragraph",
    category: "text",
    attributes: {
      content: { type: "string", source: "html", selector: "p", default: "" },
    },
    save: ({ attributes }: { attributes: Attrs }) =>
      createElement("p", {
        dangerouslySetInnerHTML: { __html: attributes.content },
      }),
  } as never);
  blocks.registerBlockType("core/group", {
    apiVersion: 3,
    title: "Group",
    category: "design",
    save: () => createElement("div", { className: "wp-block-group" }),
  } as never);
  blocks.registerBlockType("core/missing", {
    apiVersion: 3,
    title: "Unsupported",
    category: "text",
    attributes: {
      originalName: { type: "string" },
      originalUndelimitedContent: { type: "string" },
      originalContent: { type: "string", source: "raw" },
    },
    save: ({ attributes }: { attributes: Attrs }) =>
      createElement(RawHTML, null, attributes.originalContent),
  } as never);
  blocks.setUnregisteredTypeHandlerName("core/missing");
  (window as unknown as { wp: unknown }).wp = { blocks };
});

const paragraph = (html: string): string =>
  `<!-- wp:paragraph -->${html}<!-- /wp:paragraph -->`;

describe("validateBlockMarkup", () => {
  test("is unavailable without the editor registry", () => {
    const saved = (window as unknown as { wp: unknown }).wp;
    (window as unknown as { wp: unknown }).wp = undefined;
    expect(canValidateBlocks()).toBe(false);
    expect(validateBlockMarkup(paragraph("<p>Hi</p>"))).toBeNull();
    (window as unknown as { wp: unknown }).wp = saved;
  });

  test("valid core markup has no issues", () => {
    expect(canValidateBlocks()).toBe(true);
    expect(
      validateBlockMarkup(
        `${paragraph(
          "<p>Hello</p>",
        )}\n\n<!-- wp:group --><div class="wp-block-group">${paragraph(
          "<p>Inside</p>",
        )}</div><!-- /wp:group -->`,
      ),
    ).toEqual([]);
  });

  test("a save() mismatch reports the block and a short reason", () => {
    const issues = validateBlockMarkup(paragraph("<div>Hello</div>"))!;

    expect(issues).toHaveLength(1);
    expect(issues[0]).toMatchObject({
      name: "core/paragraph",
      occurrence: 1,
      path: "1",
    });
    expect(issues[0]!.reason).toContain(
      "Expected tag name `p`, instead saw `div`.",
    );
    // The catch-all dump (block type + both markups) is dropped.
    expect(issues[0]!.reason).not.toContain("Block validation failed");
    expect(issues[0]!.reason).not.toContain("Content generated by");
    expect(console).toHaveErrored();
    expect(console).toHaveWarned();
  });

  test("an unregistered block is reported by its original name", () => {
    const issues = validateBlockMarkup(
      `${paragraph(
        "<p>Ok</p>",
      )}<!-- wp:acme/widget {"size":2} --><div>x</div><!-- /wp:acme/widget -->`,
    )!;

    expect(issues).toEqual([
      {
        name: "acme/widget",
        occurrence: 1,
        path: "2",
        reason: "block type is not registered on this site",
      },
    ]);
  });

  test("nested invalid blocks get their path and per-name occurrence", () => {
    const issues = validateBlockMarkup(
      `${paragraph(
        "<p>Top</p>",
      )}<!-- wp:group --><div class="wp-block-group">${paragraph(
        "<p>Fine</p>",
      )}${paragraph('<p class="x">Broken</p>')}</div><!-- /wp:group -->`,
    )!;

    expect(issues).toHaveLength(1);
    expect(issues[0]).toMatchObject({
      name: "core/paragraph",
      occurrence: 3,
      path: "2.2",
    });
    expect(issues[0]!.reason).toMatch(/attributes/);
    expect(console).toHaveErrored();
    expect(console).toHaveWarned();
  });
});

describe("describeValidationIssues", () => {
  test("falls back to a generic reason when only the catch-all exists", () => {
    expect(
      describeValidationIssues([
        {
          args: [
            "Block validation failed for `%s` (%o).\n\nContent generated by `save` function:\n\n%s",
            "core/paragraph",
            { huge: "x".repeat(5000) },
            "<p>…</p>",
          ],
        },
      ]),
    ).toBe("saved markup does not match what the block's save() outputs");
  });

  test("caps the reason length", () => {
    const reason = describeValidationIssues([
      { args: ["Expected text `%s`, saw `%s`.", "a".repeat(500), "b"] },
      { args: ["Expected end of content, instead saw %o.", { t: "c" }] },
      { args: ["Encountered unexpected attribute `%s`.", "data-x"] },
    ]);
    expect(reason.length).toBeLessThanOrEqual(240);
  });
});

describe("formatLogArgs", () => {
  test("renders printf tokens compactly", () => {
    expect(
      formatLogArgs([
        "Expected attributes %o, instead saw %o (100%%).",
        [["class", "a"]],
        {
          type: "StartTag",
          tagName: "p",
          attributes: [],
          long: "z".repeat(200),
        },
      ]),
    ).toBe(
      `Expected attributes [["class","a"]], instead saw ${`{"type":"StartTag","tagName":"p","attributes":[],"long":"${"z".repeat(
        200,
      )}"}`.slice(0, 79)}… (100%).`,
    );
  });

  test("collapses whitespace in string args and appends extras", () => {
    expect(formatLogArgs(["Expected text `%s`.", "a\n\n  b", "extra"])).toBe(
      "Expected text `a b`. extra",
    );
  });
});

describe("formatBlockIssues", () => {
  const issue = (n: number): BlockIssue => ({
    name: "core/paragraph",
    occurrence: n,
    path: String(n),
    reason: "why",
  });

  test("one line per issue, capped", () => {
    const lines = formatBlockIssues([1, 2, 3].map(issue), 2);
    expect(lines).toEqual([
      "core/paragraph (occurrence 1, block 1): why",
      "core/paragraph (occurrence 2, block 2): why",
      "…and 1 more",
    ]);
  });
});

describe("writtenPostIds", () => {
  test("content writes yield their post id", () => {
    expect(writtenPostIds("gds__content-update", { id: 12 })).toEqual([12]);
    expect(writtenPostIds("gds/content-create", { id: 7 })).toEqual([7]);
    expect(
      writtenPostIds("gds/blocks-patch", { success: true, id: 3 }),
    ).toEqual([3]);
    // Templates: composite id, numeric wp_id.
    expect(
      writtenPostIds("gds/content-update", { id: "theme//footer", wp_id: 44 }),
    ).toEqual([44]);
  });

  test("content-replace counts only real replacements", () => {
    expect(
      writtenPostIds("gds/content-replace", { id: 5, replaced_count: 0 }),
    ).toEqual([]);
    expect(
      writtenPostIds("gds/content-replace", {
        id: 5,
        replaced_count: 2,
        dry_run: true,
      }),
    ).toEqual([]);
    expect(
      writtenPostIds("gds/content-replace", {
        posts: [
          { id: 1, matched: 2 },
          { id: 2, matched: 0 },
          { id: 3, error: "forbidden" },
        ],
      }),
    ).toEqual([1]);
  });

  test("other tools and errors are ignored", () => {
    expect(writtenPostIds("gds/content-read", { id: 1 })).toEqual([]);
    expect(writtenPostIds("gds/content-update", { error: "nope" })).toEqual([]);
    expect(writtenPostIds("gds/content-update", "ok")).toEqual([]);
  });
});

describe("buildValidationFollowUp", () => {
  test("lists issues per post with fixing instructions", () => {
    const text = buildValidationFollowUp([
      {
        postId: 12,
        issues: [
          {
            name: "acme/widget",
            occurrence: 1,
            path: "2",
            reason: "block type is not registered on this site",
          },
        ],
      },
    ]);
    expect(text.startsWith("⚠ Block validation:")).toBe(true);
    expect(text).toContain(
      "Post #12:\n- acme/widget (occurrence 1, block 2): block type is not registered on this site",
    );
    expect(text).toContain("gds/blocks-patch");
  });
});
